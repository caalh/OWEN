// Copy the browser libraries the webviews load into media/vendor/ so the
// extension works with no network: the 3D preview (three.js + OrbitControls)
// and the uPlot charts in Results, ALLEN and the Sweep Dashboard used to come
// from unpkg.com, which is exactly the host an air-gapped reactor-physics
// workstation cannot reach. Re-run after bumping either devDependency; the
// copied files are committed so a fresh clone packages without this step.
//
//   node scripts/vendor-webview-libs.mjs

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const out = join(root, 'media', 'vendor');

const files = [
    ['three/build/three.module.min.js', 'three/three.module.min.js'],
    ['three/examples/jsm/controls/OrbitControls.js', 'three/addons/controls/OrbitControls.js'],
    ['three/LICENSE', 'three/LICENSE'],
    ['uplot/dist/uPlot.iife.min.js', 'uplot/uPlot.iife.min.js'],
    ['uplot/dist/uPlot.min.css', 'uplot/uPlot.min.css'],
    ['uplot/LICENSE', 'uplot/LICENSE'],
];

for (const [from, to] of files) {
    const dst = join(out, to);
    mkdirSync(dirname(dst), { recursive: true });
    copyFileSync(join(nm, from), dst);
    console.log(`vendored ${from} -> media/vendor/${to}`);
}

const three = JSON.parse(readFileSync(join(nm, 'three/package.json'), 'utf8')).version;
const uplot = JSON.parse(readFileSync(join(nm, 'uplot/package.json'), 'utf8')).version;
writeFileSync(
    join(out, 'VERSIONS.json'),
    JSON.stringify({ three, uplot, note: 'generated by scripts/vendor-webview-libs.mjs' }, null, 2) + '\n',
);
console.log(`three ${three}, uplot ${uplot}`);
